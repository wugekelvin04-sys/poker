/* 169 手起手牌的强度百分位（千分数，越小越强）。
 * 由 tools/gen-preflop.mjs 生成：各手牌对 1 名随机对手的胜率，
 * 每手 500,000 次模拟，再按组合数加权累计。
 * 索引：对子与不同花为 hi*13+lo，同花为 lo*13+hi。 */
(function (global) {
  'use strict';
  var PCTL = [481,946,916,891,894,870,810,750,665,578,484,389,238,1000,356,858,834,846,813,789,713,641,544,459,345,190,991,955,252,774,786,762,729,698,605,526,410,330,175,973,934,879,139,716,701,668,638,593,496,392,279,145,982,943,888,822,83,644,608,590,532,477,368,264,148,964,925,867,807,759,42,557,529,465,404,342,232,116,913,903,843,783,725,662,32,462,407,351,267,187,101,855,831,798,738,677,617,554,27,348,291,220,151,86,771,747,710,695,635,566,514,437,23,235,172,104,57,686,653,626,602,575,505,428,386,309,18,142,98,45,587,541,523,493,456,419,365,300,247,199,14,78,38,474,446,401,377,339,318,276,229,160,134,113,9,35,327,288,261,208,217,184,169,125,95,75,66,54,5];

  /* 返回这手牌处在全部起手牌的前百分之几（0-1） */
  function percentile(c1, c2) {
    var r1 = c1 >> 2, r2 = c2 >> 2;
    var hi = r1 > r2 ? r1 : r2, lo = r1 > r2 ? r2 : r1;
    var suited = (c1 & 3) === (c2 & 3);
    var idx = (hi !== lo && suited) ? lo * 13 + hi : hi * 13 + lo;
    return PCTL[idx] / 1000;
  }

  global.PokerPreflop = { percentile: percentile };
})(typeof self !== 'undefined' ? self : this);
